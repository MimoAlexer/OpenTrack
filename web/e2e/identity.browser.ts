import { registerAdmission } from './fixtures';
import { randomUUID } from 'node:crypto';
import { test, expect, SavedWorkspace } from './fixtures';
import type { Bootstrap } from '../src/types';
import type { OrganizationSummary, WorkspaceDetail } from '../src/settings/types';
registerAdmission(5);

test('local password login works with every external origin blocked and recovers keyboard focus', async ({ page, saved }) => {
  const external: string[] = [];
  page.on('request', request => { if (new URL(request.url()).origin !== saved.origin) external.push('external request'); });
  await page.context().clearCookies();
  await page.goto('/signin');
  const email = page.getByRole('textbox', { name: 'Email', exact: true });
  const password = page.getByLabel('Password', { exact: true });
  await expect(email).toBeFocused();
  await email.fill('owner@example.test');
  await email.press('Tab'); await expect(password).toBeFocused();
  await password.fill('synthetic rejected password'); await password.press('Enter');
  await expect(page.getByRole('alert')).toContainText('Email or password was not accepted.');
  await expect(password).toBeFocused(); await expect(email).toHaveValue('owner@example.test');
  await password.fill(process.env.OPENTRACK_BROWSER_PASSWORD!); await password.press('Enter');
  await expect(page.getByRole('heading', { name: 'All issues', exact: true })).toBeFocused();
  await expect(page.getByRole('button', { name: /^New issue/ })).toBeEnabled();
  expect(external).toEqual([]);
});

test('rename retains saved issue URLs and switching replaces the previous workspace content', async ({ page, saved }) => {
  const organizationsResponse = await saved.http.get('/api/v1/organizations'); expect(organizationsResponse.ok()).toBe(true);
  const organizations = await organizationsResponse.json() as OrganizationSummary[];
  const name = `Identity workspace ${randomUUID().slice(0, 8)}`;
  const response = await saved.http.post('/api/v1/workspaces', { data: { organization_id: organizations[0].id, name, team_name: 'Identity Team', team_key: 'IDN' },
    headers: { 'X-CSRF-Token': saved.session.csrf_token, 'Idempotency-Key': randomUUID() } });
  expect(response.ok(), 'Create a real second workspace').toBe(true);
  const workspace = await response.json() as WorkspaceDetail;
  const bootstrapResponse = await saved.http.get(`/api/v1/workspaces/${workspace.id}/bootstrap`); expect(bootstrapResponse.ok()).toBe(true);
  const second = new SavedWorkspace(saved.http, { ...saved.session, workspaces: [workspace] }, await bootstrapResponse.json() as Bootstrap, saved.origin, workspace.id);
  const title = `Scoped identity content ${randomUUID().slice(0, 8)}`;
  const issue = await second.create(title);
  const savedPath = `/w/${workspace.id}/issues/${issue.id}`;
  await page.goto(savedPath);
  await expect(page.getByRole('textbox', { name: 'Issue title', exact: true })).toHaveValue(title);
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await page.getByRole('textbox', { name: /^Workspace name/ }).fill(`${name} renamed`);
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.locator('.workspace-identity strong')).toHaveText(`${name} renamed`);
  await page.goto(savedPath);
  await expect(page.getByRole('textbox', { name: 'Issue title', exact: true })).toHaveValue(title);
  const menu = page.locator('.workspace-menu > summary'); await menu.focus(); await menu.press('Enter');
  const select = page.getByRole('combobox', { name: 'Workspace', exact: true }); await select.focus();
  await select.selectOption(saved.workspace);
  await expect(page.getByRole('heading', { name: 'All issues', exact: true })).toBeFocused();
  await expect(page.locator('.workspace-identity strong')).toHaveText('Browser acceptance');
  await expect(page.getByRole('textbox', { name: 'Issue title', exact: true })).toHaveCount(0);
  await expect(page.getByText(title, { exact: true })).toHaveCount(0);
  await expect(page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: /Identity Team/ })).toHaveCount(0);
});

test('invitation keyboard acceptance switches accounts and member settings conceal owner actions', async ({ page, saved }) => {
  const email = `member-${randomUUID().slice(0, 8)}@example.test`;
  await page.goto(`/w/${saved.workspace}/settings/invitations`);
  const trigger = page.getByRole('button', { name: 'Create invitation', exact: true });
  await trigger.focus(); await trigger.press('Enter');
  const dialog = page.getByRole('dialog', { name: 'Invite a person', exact: true });
  const invitedEmail = dialog.getByRole('textbox', { name: 'Email', exact: true });
  await expect(invitedEmail).toBeFocused(); await invitedEmail.fill(email);
  await dialog.getByRole('button', { name: 'Create invitation', exact: true }).focus(); await page.keyboard.press('Enter');
  const created = page.getByRole('dialog', { name: 'Invitation created', exact: true });
  const token = await created.getByRole('textbox', { name: 'Single-use invitation token', exact: true }).inputValue();
  expect(!!token, 'A one-time token is issued').toBe(true);
  await created.getByRole('button', { name: 'Done', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(trigger).toBeFocused();
  await page.context().clearCookies(); await page.goto('/join');
  const tokenInput = page.getByRole('textbox', { name: 'Invitation token', exact: true });
  await expect(tokenInput).toBeFocused(); await tokenInput.fill(token);
  await page.getByRole('button', { name: 'Review invitation', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Join Browser acceptance.', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Create an account', exact: true }).focus(); await page.keyboard.press('Enter');
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Example Member');
  await page.getByLabel(/^Choose a password/).fill(process.env.OPENTRACK_BROWSER_PASSWORD!);
  await page.getByRole('button', { name: 'Create account and join', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(page.locator('.account-menu > summary')).toHaveAccessibleName('Account menu: Example Member');
  await expect(page.getByRole('button', { name: /^New issue/ })).toBeEnabled();
  await page.goto(`/w/${saved.workspace}/settings/invitations`);
  await expect(page.getByText('Workspace owners and administrators manage invitations.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Create invitation', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Members', exact: true }).click();
  await expect(page.getByText('Example Owner', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: /^Deactivate / })).toHaveCount(0);
  await page.goto('/join'); await page.getByRole('textbox', { name: 'Invitation token', exact: true }).fill(token);
  await page.getByRole('button', { name: 'Review invitation', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Invitation token', exact: true })).toBeFocused();
  await expect(page.getByRole('button', { name: 'Accept invitation', exact: true })).toHaveCount(0);
});
